"""Audit a public Pages deployment when concurrent archive updates may occur.

Research and history fetches commit independently to main. A new secondary
draw may arrive AFTER a research generation is committed but BEFORE Pages
deploys. This is a legitimate stale-research state, not a failed audit or an
excuse to present an old research number as current.
"""
from __future__ import annotations


def audit_research_pages_snapshot(
    report: dict, evolution: dict, state: dict,
) -> str:
    """Return 'fresh' or 'stale_waiting_for_next_research'; fail closed otherwise.

    Evolution MUST be independently re-read via evolution.public_status,
    which checks the append-only generation SHA chain and prediction CSV.
    State MUST be newly regenerated by build-dashboard. This function does
    not write history, issue a forecast, or change any model.
    """
    if (not isinstance(report, dict) or not isinstance(evolution, dict)
            or not isinstance(state, dict)
            or type(report.get("generation")) is not int
            or report["generation"] < 1
            or type(report.get("evaluated_draws")) is not int
            or report["evaluated_draws"] < 1
            or report.get("first_evaluated_round") != 2
            or report.get("evaluated_draws") !=
            report.get("last_evaluated_round", 0) - 1
            or evolution.get("generation") != report["generation"]
            or state.get("research_evolution") != evolution
            or report.get("production_model_changed") is not False
            or report.get("model_auto_promotion_authorized") is not False
            or evolution.get("performance_advantage_confirmed") is not False
            or evolution.get("model_auto_promotion_authorized") is not False
            or state.get("prediction_skill_confirmed") is not False
            or state.get("actual_purchase_profit_yen") is not None):
        raise ValueError("unsafe or inconsistent research deployment evidence")

    archive = state.get("historical_archive")
    if not isinstance(archive, dict):
        raise ValueError("historical archive summary missing")
    candidate = state.get("latest_research_forecast")

    if evolution.get("status") == (
            "recursive_research_exploration_not_prospective_evidence"):
        verification = evolution.get("latest_verification")
        if (not isinstance(verification, dict)
                or verification.get("generation") != report["generation"]
                or verification.get("evaluated_draws") != report["evaluated_draws"]
                or verification.get("tickets_per_draw") != 1
                or verification.get("selected_straight_hits") != (
                    report["development"]["model_metrics"]["adaptive"]["straight_hits"]
                    + report["late_historical_reanalysis"]["model_metrics"]
                    ["adaptive"]["straight_hits"])
                or verification.get("bank_primary_all_rounds_verified") is not False
                or verification.get("prediction_skill_confirmed") is not False
                or verification.get("last_round") != archive.get("last_round")
                or verification.get("archive_git_blob_sha1") !=
                archive.get("git_blob_sha1")
                or report.get("archive_latest_round") != archive.get("last_round")
                or report.get("archive_git_blob_sha1") !=
                archive.get("git_blob_sha1")
                or not isinstance(candidate, dict)
                or candidate.get("source") != "validated_research_evolution"
                or candidate.get("target_round") != archive["last_round"] + 1
                or candidate.get("data_cutoff_round") != archive["last_round"]
                or candidate.get("number") != evolution.get("next_number")
                or candidate.get("model") != evolution.get("next_model")
                or candidate.get("research_generation") != report["generation"]
                or candidate.get("actual_purchase") is not False
                or candidate.get("prediction_skill_confirmed") is not False):
            raise ValueError("fresh research snapshot failed Pages audit")
        return "fresh"

    if evolution.get("status") != "stale_history_reanalysis":
        raise ValueError("unrecognized research deployment freshness state")

    # The historical archive can legitimately advance during the workflow.
    # Do not pretend the research model was evaluated on these new rows.
    if (evolution.get("latest_verification") is not None
            or evolution.get("next_number") is not None
            or evolution.get("next_model") is not None
            or evolution.get("evaluated_draws") != 0
            or type(archive.get("last_round")) is not int
            or archive["last_round"] < report["archive_latest_round"]
            or (archive.get("last_round") == report["archive_latest_round"]
                and archive.get("git_blob_sha1") ==
                report.get("archive_git_blob_sha1"))):
        raise ValueError("a stale evolution result was advertised as current")

    # A fallback candidate is allowed ONLY if independently validated
    # by dashboard.snapshot against the latest historical replay and archive.
    if candidate is not None and (
            not isinstance(candidate, dict)
            or candidate.get("source") != "validated_single_ticket_replay"
            or candidate.get("archive_git_blob_sha1") !=
            archive.get("git_blob_sha1")
            or candidate.get("target_round") != archive["last_round"] + 1
            or candidate.get("data_cutoff_round") != archive["last_round"]
            or candidate.get("research_generation") is not None
            or candidate.get("actual_purchase") is not False
            or candidate.get("prediction_skill_confirmed") is not False):
        raise ValueError("stale research candidate leaked into public dashboard")

    return "stale_waiting_for_next_research"
